<script>
    $('#btn_submit_login').on('click', function () {
        var username = $('#modal_username').val().trim();
        var password = $('#modal_password').val().trim();
        var code = $('#modal_code').val().trim();
        var domain = $('#modal_domain').val();

        if (!username || !password || !code) {
            $('#div_login_alert').removeClass('alert-success').addClass('alert-danger').text("{{Please complete all fields.}}").show();
            return;
        }

        $('#btn_submit_login').prop('disabled', true);
        $('#spinner_login').show();
        $('#div_login_alert').hide();

        $.ajax({
            type: 'POST',
            url: 'plugins/alexa_devices/core/ajax/alexa_devices.ajax.php',
            data: {
                action: 'loginAmazon',
                username: username,
                password: password,
                code: code,
                domain: domain
            },
            dataType: 'json',
            error: function (request, status, error) {
                $('#btn_submit_login').prop('disabled', false);
                $('#spinner_login').hide();
                $('#div_login_alert').removeClass('alert-success').addClass('alert-danger').text("{{Network or communication error: " + error + "}}").show();
            },
            success: function (data) {
                $('#btn_submit_login').prop('disabled', false);
                $('#spinner_login').hide();

                if (data.state != 'ok') {
                    $('#div_login_alert').removeClass('alert-success').addClass('alert-danger').text(data.result).show();
                    return;
                }

                $('#div_login_alert').removeClass('alert-danger').addClass('alert-success').text("{{Connection established successfully. Discovering devices...}}").show();

                setTimeout(function () {
                    $('#md_modal').dialog('close');
                    if (typeof checkAlexaAuthStatus === 'function') {
                        checkAlexaAuthStatus();
                    }
                    window.location.reload();
                }, 2000);
            }
        });
    });
</script>
